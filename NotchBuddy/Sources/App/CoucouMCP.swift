/// Coucou's MCP server (docs/MCP.md): `coucou-mcp`, a stdio server agents start like any local MCP
/// server, asks the running Coucou over its socket for the Notetaker's recordings. Off by default;
/// read-only; the socket only accepts this Mac's user.
@MainActor
enum CoucouMCP {
    static let enabledKey = "coucouMCPEnabled"

    static var enabled: Bool { UserDefaults.standard.bool(forKey: enabledKey) }

    static var scriptPath: String { HookServer.supportDir.appendingPathComponent("coucou-mcp").path }

    /// One tool call from coucou-mcp, as the JSON line sent back on the socket.
    static func answer(tool: String, args: [String: Any]) -> String {
        guard enabled else {
            return reply(["ok": false, "error": "Coucou's MCP server is off: turn it on in Coucou → Agents → Coucou MCP."])
        }
        appendAppLog("nb.log", "[MCP] \(tool)")   // the tool only, never what it returns
        switch CoucouQuery.answer(tool: tool, args: args, notes: NoteTaker.shared.notes) {
        case .success(let result): return reply(["ok": true, "result": result])
        case .failure(let failure): return reply(["ok": false, "error": failure.message])
        }
    }

    private static func reply(_ object: [String: Any]) -> String {
        guard let data = try? JSONSerialization.data(withJSONObject: object, options: [.withoutEscapingSlashes]),
              let text = String(data: data, encoding: .utf8) else { return #"{"ok":false,"error":"Unreadable result."}"# }
        return text
    }

    // MARK: Setup

    /// Written at launch next to nb-hook, so agents can be pointed at it before it is turned on.
    nonisolated static func installScript() {
        let url = URL(fileURLWithPath: HookServer.supportDir.appendingPathComponent("coucou-mcp").path)
        let script = serverScript.replacingOccurrences(of: "__SOCKET__", with: HookServer.socketPath)
            .replacingOccurrences(of: "__VERSION__",
                                  with: Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "0")
        try? script.write(to: url, atomically: true, encoding: .utf8)
        _ = try? FileManager.default.setAttributes([.posixPermissions: 0o755 as NSNumber], ofItemAtPath: url.path)
    }

    /// How to add the server to each agent, for Settings' copy buttons.
    static var claudeCodeCommand: String { "claude mcp add --scope user coucou -- \"\(scriptPath)\"" }
    static var codexCommand: String { "codex mcp add coucou -- \"\(scriptPath)\"" }
    static var jsonConfig: String {
        """
        {
          "mcpServers": {
            "coucou": { "command": "\(scriptPath)" }
          }
        }
        """
    }

    // MARK: The server

    /// MCP over stdio (newline-delimited JSON-RPC 2.0), forwarding tool calls to the app.
    nonisolated private static let serverScript = #"""
#!/usr/bin/python3
# Coucou MCP server — generated by Coucou.app. Read-only access to the running Coucou's
# Notetaker: recordings, summaries, to-dos and transcripts. See docs/MCP.md.
import json, os, socket, sys

SOCKET = os.environ.get('COUCOU_SOCKET', '__SOCKET__')
VERSION = '__VERSION__'
PROTOCOL = '2025-06-18'

TOOLS = [
    {
        'name': 'list_recordings',
        'description': 'List the calls and meetings recorded by Coucou\'s Notetaker, newest first: id, title, '
                       'date, duration, speakers, a summary preview and to-do counts. Filter with query '
                       '(searches titles, summaries, to-dos and transcripts) and since.',
        'inputSchema': {
            'type': 'object',
            'properties': {
                'query': {'type': 'string', 'description': 'Text to look for, any case.'},
                'since': {'type': 'string', 'description': 'Only recordings from this date on: 2026-10-27 or ISO 8601.'},
                'limit': {'type': 'integer', 'minimum': 1, 'maximum': 100, 'default': 20},
            },
        },
