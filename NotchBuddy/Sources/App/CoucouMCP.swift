def ask_coucou(tool, arguments):
    """The running app's answer, or an error message."""
    try:
        s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        s.settimeout(15)
        s.connect(SOCKET)
        s.sendall((json.dumps({'coucou_kind': 'query', 'tool': tool, 'arguments': arguments}) + '\n').encode())
        chunks = []
        while True:
            data = s.recv(65536)
            if not data:
                break
            chunks.append(data)
            if data.endswith(b'\n'):
                break
        s.close()
        reply = json.loads(b''.join(chunks).decode() or '{}')
    except (FileNotFoundError, ConnectionRefusedError):
        return None, 'Coucou is not running. Open Coucou, then try again.'
    except Exception as e:
        return None, 'Could not reach Coucou: %s' % e
    if reply.get('ok'):
        return reply.get('result'), None
    return None, reply.get('error') or 'Coucou could not answer.'

def respond(msg_id, result=None, error=None):
    out = {'jsonrpc': '2.0', 'id': msg_id}
    if error is not None:
        out['error'] = error
    else:
        out['result'] = result
    sys.stdout.write(json.dumps(out) + '\n')
    sys.stdout.flush()

def handle(msg):
    method = msg.get('method')
    msg_id = msg.get('id')
    params = msg.get('params') or {}
    if msg_id is None:
        return  # a notification (initialized, cancelled): nothing to answer
    if method == 'initialize':
        respond(msg_id, {
            'protocolVersion': params.get('protocolVersion') or PROTOCOL,
            'capabilities': {'tools': {}},
            'serverInfo': {'name': 'coucou', 'title': 'Coucou', 'version': VERSION},
            'instructions': 'Read-only access to the calls recorded by Coucou\'s Notetaker on this Mac. '
                            'Start with list_recordings, then use the id with get_summary, get_transcript or get_todos.',
        })
    elif method == 'ping':
        respond(msg_id, {})
    elif method == 'tools/list':
        respond(msg_id, {'tools': TOOLS})
    elif method == 'tools/call':
        name = params.get('name')
        if name not in [t['name'] for t in TOOLS]:
            respond(msg_id, error={'code': -32602, 'message': 'Unknown tool: %s' % name})
            return
        result, err = ask_coucou(name, params.get('arguments') or {})
        if err:
            respond(msg_id, {'content': [{'type': 'text', 'text': err}], 'isError': True})
        else:
            respond(msg_id, {'content': [{'type': 'text', 'text': json.dumps(result, ensure_ascii=False, indent=1)}]})
    else:
        respond(msg_id, error={'code': -32601, 'message': 'Method not found: %s' % method})

def main():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except ValueError:
            respond(None, error={'code': -32700, 'message': 'Parse error'})
            continue
        try:
            handle(msg)
        except Exception as e:
            if isinstance(msg, dict) and msg.get('id') is not None:
                respond(msg.get('id'), error={'code': -32603, 'message': str(e)})

if __name__ == '__main__':
    main()
"""#
}

/// Settings → Agents → Coucou MCP.
struct CoucouMCPSettingsSection: View {
    @AppStorage(CoucouMCP.enabledKey) private var enabled = false
    @Binding var statusMessage: String

    var body: some View {
        GroupBox(String(localized: "mcp.title")) {
            VStack(alignment: .leading, spacing: 10) {
                Toggle(String(localized: "mcp.toggle"), isOn: $enabled)
                Text(String(localized: "mcp.description"))
                    .coucouText(.detail)
                    .foregroundColor(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
                Text(CoucouMCP.scriptPath)
                    .coucouText(.mono)
                    .foregroundColor(.secondary)
                    .textSelection(.enabled)
                HStack(spacing: 8) {
                    copyButton("mcp.copy-claude", CoucouMCP.claudeCodeCommand)
                    copyButton("mcp.copy-codex", CoucouMCP.codexCommand)
                    copyButton("mcp.copy-json", CoucouMCP.jsonConfig)
                }
                Text(String(localized: "mcp.json-hint"))
                    .coucouText(.detail)
                    .foregroundColor(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
            .padding(6)
        }
    }

    private func copyButton(_ key: String.LocalizationValue, _ text: String) -> some View {
        Button(String(localized: key)) {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setString(text, forType: .string)
            statusMessage = String(localized: "mcp.copied")
        }
        .coucouButton()
    }
}
