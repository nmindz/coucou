/// Coucou's MCP server (docs/MCP.md): `coucou-mcp`, a stdio server agents start like any local MCP
/// server, asks the running Coucou over its socket for the Notetaker's recordings. Off by default;
/// read-only; the socket only accepts this Mac's user.
@MainActor
enum CoucouMCP {
    static let enabledKey = "coucouMCPEnabled"

    static var enabled: Bool { UserDefaults.standard.bool(forKey: enabledKey) }

    nonisolated static var scriptPath: String { HookServer.supportDir.appendingPathComponent("coucou-mcp").path }

    /// One tool call from coucou-mcp, as the JSON line sent back on the socket.
    static func answer(tool: String, args: [String: Any]) -> String {
        guard enabled else {
            return reply(["ok": false, "error": "Coucou's MCP server is off: turn it on in Coucou → Agents → Coucou MCP."])
        }
        appendAppLog("nb.log", "[MCP] \(tool)")   // the tool only, never what it returns
        switch CoucouQuery.answer(tool: tool, args: args, notes: NoteTaker.shared.notes) {
        case .success(let result): return reply(["ok": true, "result": result])
        case .failure(let failure): return reply(["ok": false, "error": failure.message])
        }
    }

    private static func reply(_ object: [String: Any]) -> String {
        guard let data = try? JSONSerialization.data(withJSONObject: object, options: [.withoutEscapingSlashes]),
              let text = String(data: data, encoding: .utf8) else { return #"{"ok":false,"error":"Unreadable result."}"# }
        return text
    }

    // MARK: Setup

    /// Written at launch next to nb-hook, so agents can be pointed at it before it is turned on.
    nonisolated static func installScript() {
        let url = URL(fileURLWithPath: HookServer.supportDir.appendingPathComponent("coucou-mcp").path)
        let script = serverScript.replacingOccurrences(of: "__SOCKET__", with: HookServer.socketPath)
            .replacingOccurrences(of: "__VERSION__",
                                  with: Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "0")
        try? script.write(to: url, atomically: true, encoding: .utf8)
        _ = try? FileManager.default.setAttributes([.posixPermissions: 0o755 as NSNumber], ofItemAtPath: url.path)
    }

    /// For agents Settings cannot set up: their MCP settings take this JSON.
    static var jsonConfig: String { MCPConfigEdit.snippet(.cursor, script: scriptPath) }

    /// What Settings runs for Claude Code (its `~/.claude.json` is rewritten by every session).
    static var claudeCodeCommand: String { "claude mcp add --scope user coucou -- \"\(scriptPath)\"" }

    // MARK: The server

    /// MCP over stdio (newline-delimited JSON-RPC 2.0), forwarding tool calls to the app.
    nonisolated private static let serverScript = #"""
#!/usr/bin/python3
# Coucou MCP server — generated by Coucou.app. Read-only access to the running Coucou's
# Notetaker: recordings, summaries, to-dos and transcripts. See docs/MCP.md.
import json, os, socket, sys

SOCKET = os.environ.get('COUCOU_SOCKET', '__SOCKET__')
VERSION = '__VERSION__'
PROTOCOL = '2025-06-18'

TOOLS = [
    {
        'name': 'list_recordings',
        'description': 'List the calls and meetings recorded by Coucou\'s Notetaker, newest first: id, title, '
                       'date, duration, speakers, a summary preview and to-do counts. Filter with query '
                       '(searches titles, summaries, to-dos and transcripts) and since.',
        'inputSchema': {
            'type': 'object',
            'properties': {
                'query': {'type': 'string', 'description': 'Text to look for, any case.'},
                'since': {'type': 'string', 'description': 'Only recordings from this date on: 2026-10-27 or ISO 8601.'},
                'limit': {'type': 'integer', 'minimum': 1, 'maximum': 100, 'default': 20},
            },
        },
        'annotations': {'readOnlyHint': True, 'openWorldHint': False},
    },
    {
        'name': 'get_summary',
        'description': 'The summary, key points and to-dos of one recording.',
        'inputSchema': {
            'type': 'object',
            'properties': {'id': {'type': 'string', 'description': 'From list_recordings (or a unique prefix of 6+ characters).'}},
            'required': ['id'],
        },
        'annotations': {'readOnlyHint': True, 'openWorldHint': False},
    },
    {
        'name': 'get_transcript',
        'description': 'The transcript of one recording, line by line: time, speaker and text. A line whose '
                       'words were corrected after the call also carries "heard", the original transcription.',
        'inputSchema': {
            'type': 'object',
            'properties': {'id': {'type': 'string', 'description': 'From list_recordings (or a unique prefix of 6+ characters).'}},
            'required': ['id'],
        },
        'annotations': {'readOnlyHint': True, 'openWorldHint': False},
    },
    {
        'name': 'get_todos',
        'description': 'To-dos from the recordings, with owner, due date and the recording they come from. '
                       'Open ones across every recording by default; give id for one recording.',
        'inputSchema': {
            'type': 'object',
            'properties': {
                'id': {'type': 'string', 'description': 'One recording only.'},
                'include_done': {'type': 'boolean', 'default': False},
            },
        },
        'annotations': {'readOnlyHint': True, 'openWorldHint': False},
    },
]

def ask_coucou(tool, arguments):
    """The running app's answer, or an error message."""
    try:
        s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        s.settimeout(15)
        s.connect(SOCKET)
        s.sendall((json.dumps({'coucou_kind': 'query', 'tool': tool, 'arguments': arguments}) + '\n').encode())
        chunks = []
        while True:
            data = s.recv(65536)
            if not data:
                break
            chunks.append(data)
            if data.endswith(b'\n'):
                break
        s.close()
        reply = json.loads(b''.join(chunks).decode() or '{}')
    except (FileNotFoundError, ConnectionRefusedError):
        return None, 'Coucou is not running. Open Coucou, then try again.'
    except Exception as e:
        return None, 'Could not reach Coucou: %s' % e
    if reply.get('ok'):
        return reply.get('result'), None
    return None, reply.get('error') or 'Coucou could not answer.'

def respond(msg_id, result=None, error=None):
    out = {'jsonrpc': '2.0', 'id': msg_id}
    if error is not None:
        out['error'] = error
    else:
        out['result'] = result
    sys.stdout.write(json.dumps(out) + '\n')
    sys.stdout.flush()

def handle(msg):
    method = msg.get('method')
    msg_id = msg.get('id')
    params = msg.get('params') or {}
    if msg_id is None:
        return  # a notification (initialized, cancelled): nothing to answer
    if method == 'initialize':
        respond(msg_id, {
            'protocolVersion': params.get('protocolVersion') or PROTOCOL,
            'capabilities': {'tools': {}},
            'serverInfo': {'name': 'coucou', 'title': 'Coucou', 'version': VERSION},
            'instructions': 'Read-only access to the calls recorded by Coucou\'s Notetaker on this Mac. '
                            'Start with list_recordings, then use the id with get_summary, get_transcript or get_todos.',
        })
    elif method == 'ping':
        respond(msg_id, {})
    elif method == 'tools/list':
        respond(msg_id, {'tools': TOOLS})
    elif method == 'tools/call':
        name = params.get('name')
        if name not in [t['name'] for t in TOOLS]:
            respond(msg_id, error={'code': -32602, 'message': 'Unknown tool: %s' % name})
            return
        result, err = ask_coucou(name, params.get('arguments') or {})
        if err:
            respond(msg_id, {'content': [{'type': 'text', 'text': err}], 'isError': True})
        else:
            respond(msg_id, {'content': [{'type': 'text', 'text': json.dumps(result, ensure_ascii=False, indent=1)}]})
    else:
        respond(msg_id, error={'code': -32601, 'message': 'Method not found: %s' % method})

def main():
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        try:
            msg = json.loads(line)
        except ValueError:
            respond(None, error={'code': -32700, 'message': 'Parse error'})
            continue
        try:
            handle(msg)
        except Exception as e:
            if isinstance(msg, dict) and msg.get('id') is not None:
                respond(msg.get('id'), error={'code': -32603, 'message': str(e)})

if __name__ == '__main__':
    main()
"""#
